# -*- coding: utf-8 -*-
"""事業計画案（不動産取得の投資収支）の計算エンジン。

会長の既存「事業計画案」約80本の共通様式を踏襲する。
金額の単位は原則 **万円**（元文書に合わせる）。面積は㎡入力→坪を自動換算。

設計方針:
  - 各率は house-style の既定値を持ちつつ、すべて上書き可能。
  - 循環参照を避けるため「借入総額」は入力値（元文書も丸めた数字を置く）。
    自己資金は 総事業費−保証金−借入 で表示（参考）。
  - ここでは Python 値（画面プレビュー用）を返す。Excel 側は
    excel_builder が同じ式を数式として書き込み、前提を変えると再計算される。
"""

from dataclasses import dataclass, field, asdict

TSUBO = 3.305785  # 1坪 = 3.305785 ㎡


def to_tsubo(m2: float) -> float:
    """㎡ → 坪。"""
    return round((m2 or 0) / TSUBO, 2)


@dataclass
class Inputs:
    # ---- 物件概要 ----
    物件名: str = ""
    所在地: str = ""
    敷地面積: float = 0.0        # ㎡
    延床面積: float = 0.0        # ㎡
    建物構造: str = ""            # 例: RC造 地上6階
    戸数: str = ""               # 例: 14戸（ファミリータイプ）
    駐車場: str = ""             # 例: パーキング10台
    築年: str = ""               # 例: H5年3月 / 2003
    用途地域: str = ""           # 例: 第1種 / 近隣商業地域
    建ぺい率: str = ""           # 例: 60
    容積率: str = ""             # 例: 300
    交通: str = ""
    基準日: str = ""             # 例: 2024/1/10
    スキーム文: str = "上記物件を取得し、自社で運営・管理し家賃収入で借入金の返済にあたる。"

    # ---- 資金計画（万円）----
    土地代: float = 0.0
    建物代: float = 0.0
    消費税: float = 0.0          # 通常は建物代×10%（0なら自動計算）
    設備代: float = 0.0          # パーキング設備など
    保証金: float = 0.0          # 預り保証金・建設協力金（相殺）
    借入総額: float = 0.0        # 入力（丸め数字）。0なら 総事業費-保証金 を借入と仮定

    # ---- 評価額（諸費用計算用・万円）----
    土地評価額: float = 0.0
    建物評価額: float = 0.0

    # ---- 借入条件 ----
    借入金利: float = 0.5        # ％（年利）
    借入年数: int = 10

    # ---- 収入（万円）----
    月額賃料: float = 0.0
    協力金返済月: float = 0.0    # 建設協力金の月返済（収入から控除）

    # ---- 支出（年額・万円）----
    固都税土地: float = 0.0
    固都税建物: float = 0.0
    火災保険: float = 0.0
    リフォーム代: float = 0.0    # 初年度一時費用（支出計上）

    # ---- 支出（月額・万円）管理系 ----
    管理費月: float = 0.0        # EV/清掃/受水槽/消防/電気/その他の合計（月）

    # ---- 償却 ----
    法定耐用年数: int = 47       # RC47 / 重量鉄骨34 / 軽量鉄骨27 / 木22
    築年数: int = 0             # 経過年数（償却年数 = 法定 - 築年数, 下限2）

    # ---- 税金（CF用・万円）----
    法人税: float = 0.0

    # ---- 諸費用の率（％）----
    登免税土地率: float = 1.5    # 所有権移転（土地）
    登免税建物率: float = 2.0    # 移転登記（建物）
    仲介料率: float = 3.0        # 速算式 3%+6万
    仲介料加算: float = 6.0      # 万円（速算式の +6万）
    消費税率: float = 10.0       # 仲介料にかかる消費税
    抵当権率: float = 0.4        # 借入 × 0.4%
    取得税土地率: float = 3.0
    取得税建物率: float = 3.0
    土地取得税減額: float = 0.5  # 1/2（住宅用地等）。無しは 1.0

    # ---- 諸費用の固定額（万円）----
    印紙: float = 0.0            # 0 で売買価格から自動算定（2024軽減税率）
    司法書士その他: float = 20.0
    予備費: float = 0.0


def _r(x: float, nd: int = 1) -> float:
    return round(float(x or 0), nd)


def brokerage(price_man: float, rate: float, add: float, tax: float) -> float:
    """仲介手数料（万円）。宅建業法上限の速算式（realestate-calc 準拠）。

    価格>400万: 価格×rate% + add(=6万) に消費税
    200<価格<=400: 価格×4% + 2万 に消費税
    価格<=200: 価格×5% に消費税
    """
    if price_man <= 0:
        return 0.0
    t = 1 + tax / 100.0
    if price_man > 400:
        return (price_man * rate / 100.0 + add) * t
    if price_man > 200:
        return (price_man * 4 / 100.0 + 2) * t
    return price_man * 5 / 100.0 * t


def stamp_duty(price_man: float) -> float:
    """売買契約書の印紙税（万円）。2024 軽減税率（realestate-calc 準拠）。"""
    if price_man > 50000:
        return 48.0
    if price_man > 10000:
        return 16.0
    if price_man > 5000:
        return 6.0
    if price_man > 1000:
        return 3.0
    if price_man > 500:
        return 1.0
    if price_man > 100:
        return 0.5
    if price_man > 10:
        return 0.1
    return 0.02


def compute(inp: Inputs) -> dict:
    """全項目を計算して辞書で返す（画面プレビュー用）。"""
    # 消費税（未入力なら建物代×消費税率）
    shohizei = inp.消費税 if inp.消費税 else inp.建物代 * inp.消費税率 / 100.0

    # --- 諸費用内訳 ---
    登免税土地 = inp.土地評価額 * inp.登免税土地率 / 100.0
    登免税建物 = inp.建物評価額 * inp.登免税建物率 / 100.0
    baibai = inp.土地代 + inp.建物代  # 仲介料・印紙の対象（本体価格）
    仲介料 = brokerage(baibai, inp.仲介料率, inp.仲介料加算, inp.消費税率)
    # 印紙（0以下なら価格から自動算定）
    印紙 = inp.印紙 if inp.印紙 > 0 else stamp_duty(baibai)

    # 借入総額（入力優先）
    総事業費_仮 = inp.土地代 + inp.建物代 + shohizei + inp.設備代  # 諸経費は後で足す
    抵当権 = 0.0  # 借入確定後に計算

    取得税土地 = inp.土地評価額 * inp.土地取得税減額 * inp.取得税土地率 / 100.0
    取得税建物 = inp.建物評価額 * inp.取得税建物率 / 100.0

    # 借入総額: 入力があればそれ。無ければ 本体+諸費用-保証金 を借入と仮定
    諸経費_暫定 = (登免税土地 + 登免税建物 + 仲介料 + 取得税土地 + 取得税建物
                 + 印紙 + inp.司法書士その他 + inp.予備費)
    if inp.借入総額:
        借入 = inp.借入総額
    else:
        借入 = max(総事業費_仮 + 諸経費_暫定 - inp.保証金, 0)
    抵当権 = 借入 * inp.抵当権率 / 100.0

    諸経費 = (登免税土地 + 登免税建物 + 仲介料 + 抵当権 + 取得税土地 + 取得税建物
             + 印紙 + inp.司法書士その他 + inp.予備費)

    総事業費 = inp.土地代 + inp.建物代 + shohizei + inp.設備代 + 諸経費
    自己資金 = 総事業費 - inp.保証金 - 借入

    # --- 収入 ---
    年収 = (inp.月額賃料 - inp.協力金返済月) * 12.0
    満室年収 = inp.月額賃料 * 12.0

    # --- 支出 ---
    金利平均 = 借入 * inp.借入金利 / 100.0 * 0.5  # 元本×金利×年数×1/2 ÷ 年数 = 元本×金利×1/2
    償却年数 = max(inp.法定耐用年数 - inp.築年数, 2)
    償却 = inp.建物代 * 0.9 / 償却年数 if inp.建物代 else 0.0
    管理費年 = inp.管理費月 * 12.0
    運営経費 = (inp.固都税土地 + inp.固都税建物 + inp.火災保険 + 管理費年 + inp.リフォーム代)
    支出計_償却込 = 運営経費 + 金利平均 + 償却

    # --- 返済 ---
    返済年 = 借入 / inp.借入年数 if inp.借入年数 else 0.0
    返済月 = 返済年 / 12.0

    # --- 利回り（総事業費ベース）---
    def pct(n):
        return round(n / 総事業費 * 100.0, 1) if 総事業費 else 0.0

    実利回り = pct(年収 - 運営経費 - 金利平均 - 償却)
    経費込利回り = pct(年収 - 運営経費 - 金利平均)
    単純利回り = pct(年収)

    # --- キャッシュフロー（税込）---
    cf_借入あり = 年収 - 運営経費 - 金利平均 - 返済年 - inp.法人税
    cf_借入なし = 年収 - 運営経費 - inp.法人税

    return {
        "面積": {
            "敷地坪": to_tsubo(inp.敷地面積),
            "延床坪": to_tsubo(inp.延床面積),
        },
        "資金計画": {
            "土地代": _r(inp.土地代), "建物代": _r(inp.建物代), "消費税": _r(shohizei),
            "設備代": _r(inp.設備代), "保証金": _r(inp.保証金),
            "諸経費": _r(諸経費), "総事業費": _r(総事業費),
            "借入総額": _r(借入), "自己資金": _r(自己資金),
        },
        "収入": {
            "月額賃料": _r(inp.月額賃料), "協力金返済月": _r(inp.協力金返済月),
            "年収": _r(年収), "満室年収": _r(満室年収),
        },
        "支出": {
            "固都税土地": _r(inp.固都税土地), "固都税建物": _r(inp.固都税建物),
            "火災保険": _r(inp.火災保険), "管理費年": _r(管理費年),
            "リフォーム代": _r(inp.リフォーム代),
            "金利平均": _r(金利平均), "償却": _r(償却), "償却年数": 償却年数,
            "運営経費": _r(運営経費), "支出計_償却込": _r(支出計_償却込),
        },
        "返済": {"返済年": _r(返済年), "返済月": _r(返済月)},
        "利回り": {
            "実利回り": 実利回り, "経費込利回り": 経費込利回り, "単純利回り": 単純利回り,
        },
        "CF": {"借入あり": _r(cf_借入あり), "借入なし": _r(cf_借入なし)},
        "諸費用内訳": {
            "登免税土地": _r(登免税土地), "登免税建物": _r(登免税建物),
            "仲介料": _r(仲介料), "抵当権設定": _r(抵当権),
            "取得税土地": _r(取得税土地), "取得税建物": _r(取得税建物),
            "印紙": _r(印紙), "司法書士その他": _r(inp.司法書士その他),
            "予備費": _r(inp.予備費), "合計": _r(諸経費),
        },
        "入力": asdict(inp),
    }
