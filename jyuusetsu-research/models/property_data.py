# 追加資料（任意アップロード）から入る項目。**謄本だけでは埋まらない欄**を埋める。
# 本体の PROPERTY_FIELDS と分けてあるのは、こちらが「資料を上げたときだけ増える」
# 性質のもので、上げなければ存在しなくてよいため（`document_intake` 参照）。
def extend_fields(keys):
    """追加資料の項目を PropertyData の受け入れ対象に足す（重複は無視）。"""
    for key in keys or []:
        if key and key not in PROPERTY_FIELDS:
            PROPERTY_FIELDS.append(key)


def create_property_data() -> Dict[str, str]:
    """空の PropertyData を生成する。全フィールドを空文字で初期化。"""
    return {field: "" for field in PROPERTY_FIELDS}


def merge(base: Dict[str, str], updates: Dict[str, str]) -> Dict[str, str]:
    """調査サービスの戻り値を PropertyData にマージする。

    - None / 空文字は上書きしない（既存値を保護）
    - PROPERTY_FIELDS 以外のキーは無視する（構造を汚さない）
    """
    if not updates:
        return base
    for key, value in updates.items():
        if key not in PROPERTY_FIELDS:
            continue
        if value is None:
            continue
        value = str(value).strip()
        if value == "":
            continue
        base[key] = value
    return base
