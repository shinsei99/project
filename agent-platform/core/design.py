# --- 最終確認が使うチェックリスト -------------------------------------------

CHECKLIST = """【受け取り検査のチェックリスト】
A. 依頼どおりか
   - 頼まれた物になっているか（貼り紙を頼まれて提案資料になっていないか）
   - 依頼で名指しされた要素が全部入っているか（対象・条件・期限など）
B. 事故が無いか
   - 作り方の指示や設計メモが誤って印刷されていないか
   - 文字が途中で切れていないか、1文字だけ次行に落ちていないか
   - はみ出し・重なり・紙面外への流出が無いか
   - 依頼に無い具体値（金額・日数・連絡先）を勝手に作っていないか
C. 目的を果たすか
   - 一番言いたいことが、想定の距離・状況で読めるか
   - 読んだ人が次に何をすればよいか分かるか
   - 「あると効くのに無い」要素は何か（段階図・記入欄・多言語・出典など）
"""


def producing_rules(genre: str = "") -> str:
    """制作部隊のプロンプトに足す品質基準。"""
    return COMMON + "\n" + BY_GENRE.get(genre, "")


def review_checklist(genre: str = "") -> str:
    """最終確認のプロンプトに足す基準。作る側と同じ物差しで見る。"""
    return COMMON + "\n" + BY_GENRE.get(genre, "") + "\n" + CHECKLIST
