def main():
    con = sqlite3.connect(DB)
    names = {N(r[0]) for r in con.execute("SELECT name FROM properties WHERE active=1")}
    print("=" * 70)
    print(("【登録】" if GO else "【下見】") + "  物件マスタの呼び名・別名")
    print("=" * 70)
    ok = ng = 0
    for name, al in ALIASES.items():
        if N(name) not in names:
            print(f"  ★マスタに無い: {name}"); ng += 1; continue
        cur = con.execute("SELECT aliases FROM properties WHERE name=?", (name,)).fetchone()[0] or ""
        have = [x.strip() for x in cur.split("\n") if x.strip()]
        add = [a for a in al if a not in have]
        new = have + add
        print(f"  {name:<26} {'＋' + str(len(add)) if add else '  変更なし':<6} {' / '.join(new)[:60]}")
        if GO and add:
            con.execute("UPDATE properties SET aliases=? WHERE name=?", ("\n".join(new), name))
        ok += 1
    if GO:
        con.commit()
    print(f"\n  対象 {ok}物件 / マスタに無い {ng}件")
    if not GO:
        print("  ※下見のみ。--go で登録")


if __name__ == "__main__":
    main()
